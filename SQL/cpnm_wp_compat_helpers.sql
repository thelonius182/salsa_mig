-- Identity rules established from live WordPress checks:
--   Radio source set: p.post_type IN ('programma','programma_woj'),
--                     p.post_status = 'publish', p.post_date >= '2018-01-01'.
--   One physical broadcast = one post_translations term_taxonomy_id after filtering
--                            out revisions/non-radio rows.
--   broadcasts.starts_at = wp_posts.post_date.
--   broadcasts.ends_at   = postmeta pr_metadata_uitzenddatum_end.
--   pr_metadata_uitzenddatum_all_hours is a WordPress search/index aid and is ignored.
--   A replay's localized posts each point via pr_metadata_orig to the corresponding
--   localized original post.
--   episode_source_key   = post_translations group of that original post;
--                          for originals, episode_source_key = broadcast_source_key.
--   replay-of-replay mistakes are assumed to have been fixed by the existing repeat-reducer.

-- Verified example:
--   original posts 871100/871101 -> translation group 223729
--   replay posts   900119/900120 -> translation group 232571
--   therefore episode_source_key=223729 and replay broadcast_source_key=232571.

-- This script intentionally stops before creating broad radio views.
-- Reason: endpoint-time query plans over wp_posts/wp_postmeta/wp_term_relationships
-- must be designed and EXPLAINed around selective predicates to avoid large scans.
